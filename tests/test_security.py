def test_allow_external_access_opt_in(tmp_path):
    f = tmp_path / "hello.txt"
    f.write_text("hello world")
    eng = QueryEngine(allow_external_access=True).register("data", SAMPLE)
    try:
        rows = eng.query(f"SELECT content FROM read_text('{f}')")
        assert rows[0]["content"] == "hello world"
    finally:
        eng.close()


def test_security_config_object_passthrough(tmp_path):
    f = tmp_path / "hi.txt"
    f.write_text("hi")
    cfg = SecurityConfig(allow_external_access=True)
    eng = QueryEngine(security=cfg).register("data", SAMPLE)
    try:
        assert eng.query(f"SELECT content FROM read_text('{f}')")[0]["content"] == "hi"
    finally:
        eng.close()


# ---------------------------------------------------------------------------
# Resource guards
# ---------------------------------------------------------------------------


def test_query_timeout_interrupts_runaway_query():
    eng = QueryEngine(query_timeout=0.5).register("data", SAMPLE)
    try:
        t0 = time.perf_counter()
        with pytest.raises(TimeoutError):
            eng.query("SELECT count(*) FROM range(100000000000) a, range(100000) b")
        elapsed = time.perf_counter() - t0
        assert elapsed < 5.0  # interrupted quickly, not run to completion
        # Connection is reusable after an interrupt.
        assert eng.query("SELECT 1 AS x") == [{"x": 1}]
    finally:
        eng.close()


def test_timeout_none_disables_watchdog():
    eng = QueryEngine(security=SecurityConfig(query_timeout=None)).register(
        "data", SAMPLE
    )
    try:
        assert eng.query("SELECT count(*) AS c FROM data")[0]["c"] == 2
    finally:
        eng.close()


def test_memory_limit_applied():
    eng = QueryEngine(memory_limit="512MB").register("data", SAMPLE)
    try:
        setting = eng.query("SELECT current_setting('memory_limit') AS m")[0]["m"]
        # DuckDB reports it in MiB; just assert it is a bounded, small value.
        assert "GiB" not in setting or setting.startswith("0")
    finally:
        eng.close()


