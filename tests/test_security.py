# Table-name injection defence
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "bad_name",
    [
        "data; DROP TABLE data",
        "data--",
        "1data",
        "data table",
        "data'",
        "",
        "read_text",  # ok chars but still fine; keep as sanity for underscores
    ],
)
def test_invalid_table_names(bad_name):
    eng = QueryEngine()
    try:
        if bad_name == "read_text":
            # This IS a valid identifier and should be accepted.
            eng.register(bad_name, SAMPLE)
        else:
            with pytest.raises(ValueError):
                eng.register(bad_name, SAMPLE)
    finally:
        eng.close()


